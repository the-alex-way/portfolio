-- Смотрим статистические данные по полю выручка от заказа (revenue)
SELECT
    MIN(revenue) AS min_revenue,
    MAX(revenue) AS max_revenue,
    AVG(revenue) AS avg_revenue,
    PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY revenue) AS median_revenue
FROM afisha.purchases;

/*
 * РЕЗУЛЬТАТ ВЫПОЛНЕНИЯ ЗАПРОСА (статистика по выручке):
 * 
 * +-------------+------------+------------------+----------------+
 * | min_revenue | max_revenue| avg_revenue      | median_revenue |
 * +-------------+------------+------------------+----------------+
 * | -90.76      | 81174.54   | 624.83           | 355.34         |
 * +-------------+------------+------------------+----------------+
 */

/* КОММЕНТАРИЙ: в распределении выручки наблюдается значительная асимметрия: 
 * медианное значение существенно ниже среднего, что указывает на наличие крупных заказов, 
 * формирующих правый хвост распределения. Также обнаружены отрицательные значения выручки, 
 * что может быть связано с возвратами или корректировками заказов и требует 
 * отдельного учета при финансовом анализе */

