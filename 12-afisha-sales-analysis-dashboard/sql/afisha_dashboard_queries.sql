-- Распределения выручки в разрезе устройств
SELECT
    device_type_canonical,                    -- тип устройства
    SUM(revenue) AS total_revenue,            -- общая выручка с заказов
    COUNT(*) AS total_orders,                 -- количество заказов
    AVG(revenue) AS avg_revenue_per_order,    -- средняя стоимость заказа
    ROUND(
        (SUM(revenue) / SUM(SUM(revenue)) OVER ())::numeric,
        3
    ) AS revenue_share                        -- доля выручки для каждого устройства
FROM afisha.purchases
WHERE currency_code = 'rub'
GROUP BY device_type_canonical
ORDER BY revenue_share DESC;

